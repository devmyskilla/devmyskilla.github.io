import fs from 'node:fs';
import vm from 'node:vm';

const dataPath = new URL('../js/data.js', import.meta.url);
const source = fs.readFileSync(dataPath, 'utf8');
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(`${source}\nthis.__PLATFORMS__ = PLATFORMS_DATA;`, sandbox, { filename: 'js/data.js' });
const platforms = Array.isArray(sandbox.__PLATFORMS__) ? sandbox.__PLATFORMS__ : [];

const FEATURED_IDS = new Set(['plat-26','plat-25','plat-3','plat-7','plat-34','plat-30']);
const ACTIVE_MAX_ID = 40;

function sqlText(value) {
  if (value === null || value === undefined || String(value).trim() === '') return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlBool(value) {
  return value === true ? 'true' : value === false ? 'false' : 'null';
}

function stableCategory(value) {
  const map = new Map([
    ['برمجة وبيانات','technology'],
    ['تكنولوجيا','technology'],
    ['تسويق وأعمال','business'],
    ['تعليم','academic'],
    ['لغات','languages'],
    ['أعمال','business'],
    ['تقنية','technology']
  ]);
  return map.get(String(value || '').trim()) || null;
}

function normalizedLanguages(value) {
  const raw = String(value || '').trim();
  if (!raw) return [];
  const map = new Map([
    ['إنجليزي',['English']], ['الإنجليزية',['English']], ['English',['English']],
    ['عربي',['Arabic']], ['العربية',['Arabic']], ['Arabic',['Arabic']],
    ['تركي',['Turkish']], ['التركية',['Turkish']], ['Turkish',['Turkish']],
    ['متعدد اللغات',['Multilingual']], ['متعددة اللغات',['Multilingual']], ['Multilingual',['Multilingual']]
  ]);
  return map.get(raw) || [raw];
}

function sqlArray(values) {
  if (!Array.isArray(values) || !values.length) return 'null';
  return `array[${values.map(sqlText).join(',')}]::text[]`;
}

function numericId(id) {
  const match = /^plat-(\d+)$/.exec(String(id || ''));
  return match ? Number(match[1]) : null;
}

const active = platforms
  .filter(p => {
    const n = numericId(p.id);
    return n !== null && n >= 1 && n <= ACTIVE_MAX_ID;
  })
  .sort((a,b) => numericId(a.id) - numericId(b.id));

const lines = [
  '-- Generated by scripts/build-platform-seed.mjs.',
  '-- Safe presentation metadata only. Never writes expected_count, expected_count_type, or last_verified.',
  'begin;',
  ''
];

for (const p of active) {
  const n = numericId(p.id);
  const category = stableCategory(p.category);
  const languages = normalizedLanguages(p.language);
  const featured = FEATURED_IDS.has(p.id);
  lines.push(`update public.platforms`);
  lines.push('set');
  lines.push(`  description_ar = coalesce(description_ar, ${sqlText(p.description)}),`);
  lines.push(`  description_en = coalesce(description_en, ${sqlText(p.description_en)}),`);
  lines.push(`  description_tr = coalesce(description_tr, ${sqlText(p.description_tr)}),`);
  lines.push(`  category = coalesce(category, ${sqlText(category)}),`);
  lines.push(`  has_free_content = coalesce(has_free_content, ${sqlBool(p.free)}),`);
  lines.push(`  certificate_available = coalesce(certificate_available, ${sqlBool(p.certificate)}),`);
  lines.push(`  languages = coalesce(languages, ${sqlArray(languages)}),`);
  lines.push(`  logo_url = coalesce(logo_url, ${sqlText(p.thumbnail)}),`);
  lines.push(`  official_url = coalesce(official_url, ${sqlText(p.link)}),`);
  lines.push(`  featured = case when ${featured ? 'true' : 'false'} then true else featured end,`);
  lines.push(`  display_order = coalesce(display_order, ${n})`);
  lines.push(`where external_id = ${sqlText(p.id)};`);
  lines.push('');
}

lines.push('commit;');
lines.push('');
process.stdout.write(lines.join('\n'));
